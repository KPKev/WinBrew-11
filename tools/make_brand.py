"""Derive every in-app WinBrew 11 mark from the PS5 icon master."""
from pathlib import Path
from PIL import Image

def build_brand(root):
    master = Image.open(root/'sce_sys/icon0.png').convert('RGBA')
    images = [('tile', master.resize((128,128), Image.Resampling.LANCZOS)),
              ('mark', master.crop((126,126,386,386)).resize((64,64), Image.Resampling.LANCZOS))]
    lines = ['// Generated by tools/make_brand.py from sce_sys/icon0.png.\n#pragma once\n#include <cstdint>\nnamespace ww::brand {\n']
    for name, image in images:
        values = [r | (g<<8) | (b<<16) | (a<<24) for r,g,b,a in image.getdata()]
        lines.append(f'inline constexpr uint32_t {name}[{len(values)}] = {{\n')
        for i in range(0,len(values),12):
            lines.append(','.join(f'0x{v:08x}' for v in values[i:i+12])+',\n')
        lines.append('};\n')
    lines.append('}\n')
    (root/'src/brand_asset.hpp').write_text(''.join(lines),newline='\n')

if __name__ == '__main__':
    build_brand(Path(__file__).resolve().parents[1])
