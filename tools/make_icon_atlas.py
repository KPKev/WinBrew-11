"""Build exact-size, alpha-filtered icons for the shared CPU renderer."""
from pathlib import Path
from io import BytesIO
import re
from PIL import Image, ImageDraw
import resvg_py

SIZES = (20,21,22,24,29,30,34,36,40,44,46,48,58,62,64,68,112)
FONT_BYTES = 4*96*48*56

def svg(root, name, color=None):
    source=(root/'art/icons'/name).read_text()
    if color:
        source=re.sub(r'fill="[^"]*"',f'fill="{color}"',source)
        source=source.replace('<svg ',f'<svg fill="{color}" ',1) if 'fill=' not in source.split('>')[0] else source
    return Image.open(BytesIO(resvg_py.svg_to_bytes(svg_string=source,width=512,height=512))).convert('RGBA')

def fit(image, fill=.92, crop=False):
    image=image.convert('RGBA')
    if crop:
        bounds=image.getchannel('A').point(lambda a:255 if a>96 else 0).getbbox()
        if bounds: image=image.crop(bounds)
    scale=min(512*fill/image.width,512*fill/image.height)
    image=image.resize((round(image.width*scale),round(image.height*scale)),Image.Resampling.LANCZOS)
    canvas=Image.new('RGBA',(512,512));canvas.alpha_composite(image,((512-image.width)//2,(512-image.height)//2))
    return canvas

def build_icons(root):
    art=root/'art/icons'
    icons=[Image.new('RGBA',(512,512))]
    icons += [fit(Image.open(art/(name+'.png')),crop=True) for name in ('pc','recycle')]
    icons += [fit(Image.open(art/'playden.png'),.98),fit(Image.open(art/'quake-rtx.png'),.94,crop=True)]
    icons += [fit(Image.open(art/(name+'.png')),crop=True) for name in ('folder','settings')]
    icons += [fit(svg(root,'search.svg','#ffffff'),.96),fit(svg(root,'chrome.svg'),.94)]
    wiki=Image.new('RGBA',(512,512));ImageDraw.Draw(wiki).ellipse((20,20,492,492),fill=(250,251,253,255))
    word=fit(svg(root,'wiki.svg','#22252b'),.73);wiki.alpha_composite(word);icons.append(wiki)
    youtube=Image.new('RGBA',(512,512));ImageDraw.Draw(youtube).rounded_rectangle((72,127,440,385),65,fill='white')
    youtube.alpha_composite(svg(root,'youtube.svg','#ff0033'));icons.append(fit(youtube,.94))
    icons += [fit(svg(root,name+'.svg','#ffffff'),.96) for name in ('wifi','speaker','wifi_off','speaker_mute','network_adapter','controller')]
    data=bytearray((root/'assets/font.bin').read_bytes()[:FONT_BYTES])
    assert len(data)==FONT_BYTES and len(icons)==17
    for image in icons:
        for size in SIZES:
            # Pillow filters RGBA in premultiplied alpha, avoiding bright/dark fringes.
            data.extend(image.resize((size,size),Image.Resampling.LANCZOS).tobytes())
    (root/'assets/font.bin').write_bytes(data)
    header='''// Generated by tools/make_icon_atlas.py.\n#pragma once\n#include <cstddef>\nnamespace ww::icons {\n'''
    header+=f'inline constexpr int Sizes[] = {{{",".join(map(str,SIZES))}}};\n'
    header+=f'inline constexpr int Levels={len(SIZES)}, Count=17;\ninline constexpr size_t FontBytes={FONT_BYTES}, Bytes={len(data)};\n'
    header+='inline constexpr size_t offset(int kind,int level) { size_t block=0,before=0; for(int i=0;i<Levels;++i) {size_t n=size_t(Sizes[i])*Sizes[i]*4;block+=n;if(i<level)before+=n;}return FontBytes+kind*block+before;}\n}\n'
    (root/'src/icon_layout.hpp').write_text(header,newline='\n')
    # Review against both app themes at the actual desktop and taskbar sizes.
    sheet=Image.new('RGBA',(1024,380),'#e8eef7');d=ImageDraw.Draw(sheet)
    names=['This PC','Recycle Bin','Playden','Quake II RTX','Explorer','Settings','Search','Web']
    for i,name in enumerate(names):
        for row,bg in [(0,'#e8eef7'),(1,'#20242e')]:
            x=i*128;y=row*190;d.rectangle((x,y,x+127,y+189),fill=bg)
            for size,dy in [(64,12),(36,92),(29,140)]:
                layer=icons[i+1].resize((size,size),Image.Resampling.LANCZOS)
                if i==6 and row==0:
                    layer.putdata([(35,42,54,a) for _,_,_,a in layer.getdata()])
                sheet.alpha_composite(layer,(x+(128-size)//2,y+dy))
            d.text((x+6,y+174),name,fill='white' if row else '#20242e')
    sheet.convert('RGB').save(root/'art/icons/preview.png')
    print(f'Built filtered icon atlas: {len(data)} bytes; no runtime image decoding')

if __name__=='__main__': build_icons(Path(__file__).resolve().parents[1])
