#!/usr/bin/env python3
"""Author the pinned compatibility payload from verified local build outputs.

No console access or publication. The full runtime remains a release asset;
Git contains its manifest, generated C++ table and corresponding-source pins.
"""
import argparse
import hashlib
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
KIT_SHA = '2dcb3ebb423547349faf41c20959f54399daaee1dbe9772ec53156350cb1685a'
WINE_SHA = '662dc2757e5307cb53c8ed5add168cbb0aca4f997d208ed27ab916c31a4a6982'
WIN32U_SHA = '3f942103da2f100fdb68abe4fee91e0716a050e97a6c83acd26fcd90787f5af4'
def sha(data): return hashlib.sha256(data).hexdigest()
def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, sort_keys=True)+'\n', newline='\n')

def create(kit, wine, launcher, module, output):
    if output.exists(): raise ValueError('Output exists; choose a new release archive')
    if sha(kit.read_bytes()) != KIT_SHA or sha(wine.read_bytes()) != WINE_SHA:
        raise ValueError('Upstream runtime input differs')
    patched = module.read_bytes()
    if sha(patched) != WIN32U_SHA: raise ValueError('Cursor module differs from the owner-confirmed build')
    payload, modes = {}, {}
    with zipfile.ZipFile(wine) as z:
        for n in z.namelist():
            if n.endswith('/'): continue
            prefix='wine-cs2-019.stage/'
            if not n.startswith(prefix): raise ValueError('Unexpected Wine archive path')
            rel=n[len(prefix):]
            payload[rel]=z.read(n);modes[rel]=z.getinfo(n).external_attr>>16 & 0o777
    module_path='lib/wine/x86_64-unix/win32u.prx'
    payload[module_path]=patched
    inventory=json.loads(payload['runtime-inventory.json'])
    inventory[module_path]=WIN32U_SHA
    payload['runtime-inventory.json']=(json.dumps(inventory,indent=2,sort_keys=True)+'\n').encode()
    modes['runtime-inventory.json']=0o644
    runtime_paths=sorted(payload)
    with zipfile.ZipFile(kit) as z:
        prefix='playden-kit-0.19/playden-kit/titles/any-title-7537eb0/win/'
        manifest=json.loads(z.read(prefix+'mesa-zink-manifest.json'))
        if manifest['mesa_commit'] != '4778ff0a643eb7eb45d43c412d4d3d776444060c':
            raise ValueError('Unexpected Mesa source')
        for rel, spec in manifest['files'].items():
            data=z.read(prefix+'mesa-zink/'+rel)
            if sha(data)!=spec['sha256']: raise ValueError('Mesa DLL differs')
            name='title/win/mesa-zink/'+rel;payload[name]=data;modes[name]=0o644
        name='title/win/mesa-zink-manifest.json'
        payload[name]=z.read(prefix+'mesa-zink-manifest.json');modes[name]=0o644
    for rel in ['eboot.bin','native-title-build.json']:
        name='title/'+rel;payload[name]=(launcher/rel).read_bytes();modes[name]=0o755 if rel=='eboot.bin' else 0o644
    def entry(n): return dict(path=n,size=len(payload[n]),sha256=sha(payload[n]),mode=f'{modes[n]:04o}')
    manifest=dict(schema='vapor-game-compatibility/1',id='blender-019.1',steam_app_id=365670,
        upstream_kit_sha256=KIT_SHA,upstream_wine_archive_sha256=WINE_SHA,
        files=[entry(n) for n in runtime_paths],
        title_files=[entry(n) for n in sorted(payload) if n.startswith('title/')],
        qualification=dict(owner_confirmed=['stable workspace','smooth pointer and menus','responsive wheel zoom'],
          not_established=['large-scene stability','rendering/export','cause of one prior unexpected exit'],
          delivery='portable production launcher and installer verified separately; not console-deployed'),
        source_receipt='runtime-patches/blender/source-receipt.json')
    raw=(json.dumps(manifest,indent=2,sort_keys=True)+'\n').encode();pin=sha(raw)
    mpath=ROOT/'assets/blender-runtime/manifest.json';mpath.parent.mkdir(parents=True,exist_ok=True);mpath.write_bytes(raw)
    for n in ['vapor-runtime.json','title/vapor-compatibility.json']:payload[n]=raw;modes[n]=0o644
    order=runtime_paths+['vapor-runtime.json']+sorted(n for n in payload if n.startswith('title/') and n!='title/vapor-compatibility.json')+['title/vapor-compatibility.json']
    output.parent.mkdir(parents=True,exist_ok=True)
    with zipfile.ZipFile(output,'x',zipfile.ZIP_DEFLATED,compresslevel=6) as z:
        for n in order:
            info=zipfile.ZipInfo(n,(2026,11,7,0,0,0));info.create_system=3
            info.external_attr=(0o100000|modes[n])<<16;info.compress_type=zipfile.ZIP_DEFLATED
            z.writestr(info,payload[n])
    archive_pin=sha(output.read_bytes())
    p=ROOT/'tools/prepare_blender_runtime.py';s=p.read_text()
    import re
    s=re.sub(r"MANIFEST_SHA256 = '[0-9a-f]+'",f"MANIFEST_SHA256 = '{pin}'",s)
    s=re.sub(r"ARCHIVE_SHA256 = '[0-9a-f]+'",f"ARCHIVE_SHA256 = '{archive_pin}'",s)
    p.write_text(s,newline='\n')
    h=['// Generated by tools/create-blender-runtime-release.py; do not hand edit.','#pragma once',
       '#include "runtime/package_installer.h"','namespace ww::steam_integration {',
       f'inline constexpr const char* kBlenderRuntimeManifestSha256 = "{pin}";']
    for group, names in [('BlenderRuntimeFiles',[n for n in order if not n.startswith('title/')]),
                         ('BlenderTitleFiles',[n for n in order if n.startswith('title/')])]:
        h+=['inline std::vector<playden::runtime::KitFile> '+group+'() { return {']
        h += [f'  {{"{n}", {len(payload[n])}, "{sha(payload[n])}", {modes[n]:04o}}},' for n in names]
        h+=['}; }']
    h+=['inline void ConfigureBlenderRuntime(playden::runtime::FilesystemPackageInstaller& installer, const std::filesystem::path& runtime) {',
        '  installer.SetGameRuntimeOverride({365670, runtime / "compatibility/steam-365670-blender-v1", "blender-019.1", kBlenderRuntimeManifestSha256, BlenderRuntimeFiles(), BlenderTitleFiles()});','}','}']
    (ROOT/'src/steam_integration/blender_runtime_files.hpp').write_text('\n'.join(h)+'\n',newline='\n')
    helper=ROOT/'tools/fix-vapor-install-modes.py'
    if helper.exists(): helper.write_text(re.sub(r"BLENDER_PIN = '[0-9a-f]+'",f"BLENDER_PIN = '{pin}'",helper.read_text()),newline='\n')
    print('Pinned',len(payload),'files; archive SHA256',archive_pin,'manifest',pin)

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--kit',type=Path,required=True);p.add_argument('--wine',type=Path,required=True)
    p.add_argument('--launcher',type=Path,required=True);p.add_argument('--module',type=Path,required=True)
    p.add_argument('--output',type=Path,required=True);a=p.parse_args()
    create(a.kit,a.wine,a.launcher,a.module,a.output)
